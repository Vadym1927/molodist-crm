def _rows(db: Session) -> dict[int, float]:
    """Ціни консультацій з прайсу (той самий розрахунок, що на сторінці BEAUTY PLAN)."""
    try:
        return {r["id"]: r["price"] for g in sp.prices(db, sp.PAGES["beautyplan"]) for r in g["rows"]}
    except Exception:  # noqa: BLE001
        return {}


def data(db: Session, lp: dict, home: dict, base: str) -> dict:
    """Дані сторінки поверх даних головної: ціни, лікар, відгуки й товари про акне, FAQ."""
    from . import online_booking as ob
    prices = _rows(db)
    c = lp["consult"]
    formats = [{"id": i, "t": t, "d": d, "price": prices.get(i)} for i, t, d in c["formats"]]
    main_price = prices.get(c["main_id"])
    # процедури — позиції з прайсу CRM за розділами
    try:
        pl = ob.pricelist(db)
    except Exception:  # noqa: BLE001
        pl = []
    procs = []
    for g in lp["procs"]["groups"]:
        items = [i for cat in pl if any(k in cat["name"].lower() for k in g["cat"]) for i in cat["items"]]
        if not items:
            items = [i for cat in pl for i in cat["items"] if any(k in i["name"].lower() for k in g["cat"])]
        top, n = g.get("top") or [], g.get("n", 8)

        def _rank(x, top=top):                       # спершу найзапитуваніші зони (за порядком у "top"), далі за ціною
            low = x["name"].lower()
            return (next((k for k, w in enumerate(top) if w in low), len(top)), x["price"], x["name"])
        items = sorted({i["id"]: i for i in items}.values(), key=_rank)
        procs.append({**g, "items": items[:n], "more": max(0, len(items) - n), "lo": min((i["price"] for i in items), default=None)})
    # лікар
    doc = [d for d in home.get("team") or [] if re.search(lp["doctor"]["match"], (d.get("name") or "").lower())][:lp["doctor"].get("n", 1)]
    # кейси: файли сайту або фото, вирізані з карток архіву Tilda (немає оригіналу — кейс не показуємо)
    from . import site_crops as sc
    st_ = home.get("st") or (lambda n: n)
    cases = []
    for x in lp["cases"]["items"]:
        src = [sc.url(f"{x['crop']}-{i}.webp", base) for i in (1, 2)] if x.get("crop") else [st_(n) for n in x["ba"]]
        if all(src):
            cases.append({**x, "src": src})
    # відгуки: 8 з Google (5★), спершу про акне або де згадують лікаря, далі найсвіжіші
    rev = home.get("rev")
    if rev and rev.get("reviews"):
        kw = re.compile(lp["reviews_kw"] + "|" + lp["reviews_doc"], re.I)
        rel = [r for r in rev["reviews"] if kw.search(r.get("text") or "")]
        rev = {**rev, "reviews": (rel + [r for r in rev["reviews"] if r not in rel])[:8], "n_rel": len(rel)}
    # + відгуки пацієнтів з опитування після візиту (архів CRM): до Софії Сирової або про акне — анонімно
    acne = lp["key"] == "akne"
    lik = lp.get("reviews_ilike") or ["%софі%", "%акне%", "%прищ%", "%висип%"]
    try:
        from sqlalchemy import select, or_
        from ..models import ReviewArchive
        q = (select(ReviewArchive).where(ReviewArchive.text.is_not(None), ReviewArchive.avg >= 5, ReviewArchive.hidden.is_not(True),
                                         or_(*[ReviewArchive.text.ilike(k) for k in lik], *([ReviewArchive.doctor_name.ilike("%сиров%")] if acne else [])))
             .order_by(ReviewArchive.at.desc().nullslast(), ReviewArchive.id.desc()).limit(12))
        own = [{"author": "Відгук після візиту", "when": x.at.strftime("%m.%Y") if x.at else "", "rating": 5, "src": "crm",
                "text": " ".join((x.text or "").split())} for x in db.scalars(q) if len((x.text or "").strip()) >= 40]
        # відгуки з опитування CRM після візиту: усі оцінки «5», є коментар, лікар — Сирова або текст про акне
        from ..models import Review, Doctor
        doc_ids = [d.id for d in db.scalars(select(Doctor)) if "сиров" in (d.name or "").lower()] if acne else []
        q2 = (select(Review).where(Review.text.is_not(None), Review.avg >= 5,
                                   or_(Review.doctor_id.in_(doc_ids or [-1]), *[Review.text.ilike(k) for k in lik]))
              .order_by(Review.answered_at.desc().nullslast()).limit(12))
        own += [{"author": "Відгук після візиту", "when": x.answered_at.strftime("%m.%Y") if x.answered_at else "", "rating": 5, "src": "crm",
                 "text": " ".join((x.text or "").split())} for x in db.scalars(q2) if len((x.text or "").strip()) >= 40]
    except Exception:  # noqa: BLE001
        own = []
    own = [x for x in own if not re.search(r"[ыэъё]", x["text"], re.I)]      # лише українською
    if own:
        g = (rev or {}).get("reviews") or []
        k = (rev or {}).get("n_rel", 0)
        rev = {**(rev or {"rating": 5.0, "count": 0, "url": ""}), "reviews": (g[:k] + own[:4] + g[k:])[:9]}
    # товари: засоби для проблемної шкіри; якщо мало — добираємо хітами
    products = home.get("products") or []
    try:
        from . import shop_front as sf
        kw = re.compile(lp["products_kw"], re.I)
        pool = sorted((i for i in sf.catalog(db)["items"] if i.get("stock") and i.get("imgs")),
                      key=lambda i: (-(i.get("sold") or 0), -i["new"]))
        no = re.compile(lp["products_no"], re.I)
        hit = [i for i in pool if kw.search(" ".join(str(i.get(k) or "") for k in ("name", "desc", "seo_desc", "sections")))
               and not no.search(str(i.get("name") or ""))]
        products = hit[:8]                            # лише засоби для лікування й догляду при акне; немає — блок товарів сховано
    except Exception:  # noqa: BLE001
        pass
    about = [{"t": t, "d": d, "img": (sc.url(i[5:], base) if i.startswith("crop:") else st_(i)) if i else ""}
             for t, d, *rest in (lp.get("about") or {}).get("items", []) for i in [rest[0] if rest else ""]]
    money = sp.money
    faq = [(q, a.format(price=money(main_price) if main_price else "за прайсом",
                        price_online=money(prices.get(568)) if prices.get(568) else "за прайсом")) for q, a in lp["faq"]]
    hero = next((u for u in (sp.media_url(n, base) for n in lp["hero"]["media"]) if u), "")
    if not hero and lp["hero"].get("crop"):
        hero = sc.url(lp["hero"]["crop"], base)
    return {"hero_img": hero, "cases": cases, "about_items": about, "formats": formats, "main_price": main_price, "procs": procs, "lp_doc": doc, "rev": rev, "products": products, "faq": faq}


def jsonld(lp: dict, c: dict, url: str, faq: list, formats: list) -> str:
    """schema.org: медична сторінка про акне, заклад, хлібні крихти, FAQ і ціни консультацій."""
    root = c["canonical"].rstrip("/") + "/"
    org = {"@type": "MedicalClinic", "@id": root + "#org", "name": "MOLODIST", "url": root, "telephone": c["phone"],
           "address": {"@type": "PostalAddress", "streetAddress": "вул. Князя Романа Мстиславича, 28А", "addressLocality": "Київ",
                       "addressCountry": "UA"}}
    offers = [{"@type": "Offer", "name": f["t"], "price": f["price"], "priceCurrency": "UAH"} for f in formats if f["price"]]
    page = {"@type": "MedicalWebPage", "url": url, "name": lp["seo"]["title"], "description": lp["seo"]["desc"], "inLanguage": "uk",
            "about": {"@type": "MedicalCondition", "name": (lp.get("about_ld") or {}).get("name", "Акне"),
                      "alternateName": (lp.get("about_ld") or {}).get("alt", ["Вугрова хвороба", "Постакне"])},
            "audience": {"@type": "Patient"}, "provider": {"@id": org["@id"]}}
    if offers:
        page["offers"] = offers
    crumbs = {"@type": "BreadcrumbList", "itemListElement": [
        {"@type": "ListItem", "position": 1, "name": "MOLODIST", "item": root},
        {"@type": "ListItem", "position": 2, "name": lp["hero"]["h1"], "item": url}]}
    fq = {"@type": "FAQPage", "mainEntity": [{"@type": "Question", "name": q, "acceptedAnswer": {"@type": "Answer", "text": a}} for q, a in faq]}
    return json.dumps({"@context": "https://schema.org", "@graph": [org, page, crumbs, fq]}, ensure_ascii=False)

def _rows(db: Session) -> dict[int, float]:
    """Ціни консультацій з прайсу (той самий розрахунок, що на сторінці BEAUTY PLAN)."""
    try:
        return {r["id"]: r["price"] for g in sp.prices(db, sp.PAGES["beautyplan"]) for r in g["rows"]}
    except Exception:  # noqa: BLE001
        return {}


def data(db: Session, lp: dict, home: dict, base: str) -> dict:
    """Дані сторінки поверх даних головної: ціни, лікар, відгуки й товари про акне, FAQ."""
    from . import online_booking as ob
    prices = _rows(db)
    c = lp["consult"]
    formats = [{"id": i, "t": t, "d": d, "price": prices.get(i)} for i, t, d in c["formats"]]
    main_price = prices.get(c["main_id"])
    # процедури — позиції з прайсу CRM за розділами
    try:
        pl = ob.pricelist(db)
    except Exception:  # noqa: BLE001
        pl = []
    procs = []
    for g in lp["procs"]["groups"]:
        items = [i for cat in pl if any(k in cat["name"].lower() for k in g["cat"]) for i in cat["items"]]
        if not items:
            items = [i for cat in pl for i in cat["items"] if any(k in i["name"].lower() for k in g["cat"])]
        items = sorted({i["id"]: i for i in items}.values(), key=lambda x: (x["price"], x["name"]))
        procs.append({**g, "items": items[:8], "more": max(0, len(items) - 8), "lo": min((i["price"] for i in items), default=None)})
    # лікар
    doc = [d for d in home.get("team") or [] if lp["doctor"]["match"] in (d.get("name") or "").lower()]
    # відгуки: спершу ті, де пишуть про акне / шкіру, далі решта
    rev = home.get("rev")
    if rev and rev.get("reviews"):
        kw = re.compile(lp["reviews_kw"], re.I)
        rel = [r for r in rev["reviews"] if kw.search(r.get("text") or "")]
        rev = {**rev, "reviews": rel + [r for r in rev["reviews"] if r not in rel]}
    # товари: засоби для проблемної шкіри; якщо мало — добираємо хітами
    products = home.get("products") or []
    try:
        from . import shop_front as sf
        kw = re.compile(lp["products_kw"], re.I)
        pool = sorted((i for i in sf.catalog(db)["items"] if i.get("stock") and i.get("imgs")),
                      key=lambda i: (-(i.get("sold") or 0), -i["new"]))
        hit = [i for i in pool if kw.search(" ".join(str(i.get(k) or "") for k in ("name", "brand", "desc", "seo_desc", "sections")))]
        products = (hit + [i for i in products if i not in hit])[:8] if hit else products
    except Exception:  # noqa: BLE001
        pass
    money = sp.money
    faq = [(q, a.format(price=money(main_price) if main_price else "за прайсом",
                        price_online=money(prices.get(568)) if prices.get(568) else "за прайсом")) for q, a in lp["faq"]]
    return {"formats": formats, "main_price": main_price, "procs": procs, "lp_doc": doc, "rev": rev, "products": products, "faq": faq}


def jsonld(lp: dict, c: dict, url: str, faq: list, formats: list) -> str:
    """schema.org: медична сторінка про акне, заклад, хлібні крихти, FAQ і ціни консультацій."""
    root = c["canonical"].rstrip("/") + "/"
    org = {"@type": "MedicalClinic", "@id": root + "#org", "name": "MOLODIST", "url": root, "telephone": c["phone"],
           "address": {"@type": "PostalAddress", "streetAddress": "вул. Князя Романа Мстиславича, 28А", "addressLocality": "Київ",
                       "addressCountry": "UA"}}
    offers = [{"@type": "Offer", "name": f["t"], "price": f["price"], "priceCurrency": "UAH"} for f in formats if f["price"]]
    page = {"@type": "MedicalWebPage", "url": url, "name": lp["seo"]["title"], "description": lp["seo"]["desc"], "inLanguage": "uk",
            "about": {"@type": "MedicalCondition", "name": "Акне", "alternateName": ["Вугрова хвороба", "Постакне"]},
            "audience": {"@type": "Patient"}, "provider": {"@id": org["@id"]}}
    if offers:
        page["offers"] = offers
    crumbs = {"@type": "BreadcrumbList", "itemListElement": [
        {"@type": "ListItem", "position": 1, "name": "MOLODIST", "item": root},
        {"@type": "ListItem", "position": 2, "name": lp["hero"]["h1"], "item": url}]}
    fq = {"@type": "FAQPage", "mainEntity": [{"@type": "Question", "name": q, "acceptedAnswer": {"@type": "Answer", "text": a}} for q, a in faq]}
    return json.dumps({"@context": "https://schema.org", "@graph": [org, page, crumbs, fq]}, ensure_ascii=False)

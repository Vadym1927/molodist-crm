def jsonld(lp: dict, c: dict, url: str, faq: list, formats: list, videos: list | None = None) -> str:
    """schema.org: медична сторінка про акне, заклад, хлібні крихти, FAQ і ціни консультацій."""
    root = c["canonical"].rstrip("/") + "/"
    org = {"@type": "MedicalClinic", "@id": root + "#org", "name": "MOLODIST", "url": root, "telephone": c["phone"],
           "address": {"@type": "PostalAddress", "streetAddress": "вул. Князя Романа Мстиславича, 28А", "addressLocality": "Київ",
                       "addressCountry": "UA"}}
    offers = [{"@type": "Offer", "name": f["t"], "price": f["price"], "priceCurrency": "UAH"} for f in formats if f["price"]]
    page = {"@type": "MedicalWebPage", "url": url, "name": lp["seo"]["title"], "description": lp["seo"]["desc"], "inLanguage": "uk",
            "about": {"@type": (lp.get("about_ld") or {}).get("type", "MedicalCondition"), "name": (lp.get("about_ld") or {}).get("name", "Акне"),
                      "alternateName": (lp.get("about_ld") or {}).get("alt", ["Вугрова хвороба", "Постакне"])},
            "audience": {"@type": "Patient"}, "provider": {"@id": org["@id"]}}
    if offers:
        page["offers"] = offers
    crumbs = {"@type": "BreadcrumbList", "itemListElement": [
        {"@type": "ListItem", "position": 1, "name": "MOLODIST", "item": root},
        {"@type": "ListItem", "position": 2, "name": lp["hero"]["h1"], "item": url}]}
    fq = {"@type": "FAQPage", "mainEntity": [{"@type": "Question", "name": q, "acceptedAnswer": {"@type": "Answer", "text": a}} for q, a in faq]}
    vids = [{"@type": "VideoObject", "name": v["name"], "description": v["desc"], "thumbnailUrl": [v["thumb"]], "contentUrl": v["src"],
             "uploadDate": v["date"], "inLanguage": "uk", "publisher": {"@id": org["@id"]}, **({"embedUrl": v["url"]} if v.get("url") else {})}
            for v in videos or [] if v.get("src") and v.get("thumb") and v.get("date")]   # Google: відео в пошуку — потрібні прев'ю й дата
    return json.dumps({"@context": "https://schema.org", "@graph": [org, page, crumbs, fq, *vids]}, ensure_ascii=False)


def full_price(db: Session, base: str = "") -> dict:
    """Повний прайс для сторінки /price: розділи з CRM (назви без брендів ботулотоксину), швидкий вибір за запитом і акція епіляції."""
    from . import online_booking as ob, site_home as sh
    try:
        online = {s_["id"] for cat in ob.catalog(db)["cats"] for s_ in cat["items"]}
    except Exception:  # noqa: BLE001
        online = set()
    try:
        groups = ob.pricelist(db, online)
    except Exception:  # noqa: BLE001
        groups = []
    slug = lambda t: re.sub(r"[^a-z0-9]+", "-", _translit(t).lower()).strip("-")
    pg = sp.PAGES.get("laserepilation") or {}
    promo = pg.get("promo") if sp._promo_on(pg.get("promo")) else None
    for g in groups:
        g["id"] = "p-" + slug(g["name"])
        g["promo"] = promo if promo and "лазерна епіляція" in g["name"].lower() else None
    concerns = [{"t": x["t"], "href": f"{base}/{x.get('page') or x.get('slug')}"} for x in sh.CONCERNS if x.get("page") or x.get("slug")]
    from datetime import date as _d
    return {"groups": groups, "concerns": concerns, "n": sum(len(g["items"]) for g in groups), "date": _d.today().strftime("%d.%m.%Y")}


_TR = dict(zip("абвгґдеєжзиіїйклмнопрстуфхцчшщьюя", ["a", "b", "v", "h", "g", "d", "e", "ie", "zh", "z", "y", "i", "i", "i", "k", "l", "m", "n", "o",
                                                      "p", "r", "s", "t", "u", "f", "kh", "ts", "ch", "sh", "shch", "", "iu", "ia"]))


def _translit(t: str) -> str:
    return "".join(_TR.get(ch, ch) for ch in (t or "").lower())


def _plural(n: int, one: str, few: str, many: str) -> str:
    return one if n % 10 == 1 and n % 100 != 11 else few if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14 else many


def crm_reviews(db: Session, cfg: dict) -> dict | None:
    """Відгуки з опитувань після візиту (архів CleverBox + опитування CRM): лише 5★ і з текстом, де згадано лікаря."""
    from sqlalchemy import select, or_
    from ..models import ReviewArchive, Review
    pat = cfg.get("ilike") or []
    try:
        a = db.scalars(select(ReviewArchive).where(ReviewArchive.text.is_not(None), ReviewArchive.avg >= 5, ReviewArchive.hidden.is_not(True),
                                                   or_(*[ReviewArchive.text.ilike(k) for k in pat]))
                       .order_by(ReviewArchive.at.desc().nullslast(), ReviewArchive.id.desc())).all()
        b = db.scalars(select(Review).where(Review.text.is_not(None), Review.avg >= 5, or_(*[Review.text.ilike(k) for k in pat]))
                       .order_by(Review.answered_at.desc().nullslast())).all()
    except Exception:  # noqa: BLE001
        return None
    items, seen = [], set()
    for x in b:
        items.append({"author": "Відгук після візиту", "when": x.answered_at.strftime("%m.%Y") if x.answered_at else "", "rating": 5, "src": "crm",
                      "text": " ".join((x.text or "").split())})
    for x in a:
        items.append({"author": "Відгук після візиту", "when": x.at.strftime("%m.%Y") if x.at else "", "rating": 5, "src": "crm",
                      "text": " ".join((x.text or "").split())})
    out = []
    for r in items:
        k = re.sub(r"\W+", "", r["text"].lower())[:120]
        if len(r["text"]) < 30 or k in seen or re.search(r"[ыэъё]", r["text"], re.I):
            continue
        seen.add(k)
        out.append(r)
    if not out:
        return None
    try:                                              # рейтинг — середня ВСІХ оцінок у відгуках, де згадано лікаря (не лише «5»)
        from sqlalchemy import func
        n1, s1 = db.execute(select(func.count(ReviewArchive.id), func.sum(ReviewArchive.avg)).where(
            ReviewArchive.avg.is_not(None), or_(*[ReviewArchive.text.ilike(k) for k in pat]))).one()
        n2, s2 = db.execute(select(func.count(Review.id), func.sum(Review.avg)).where(
            Review.avg.is_not(None), or_(*[Review.text.ilike(k) for k in pat]))).one()
        n = int(n1 or 0) + int(n2 or 0)
        avg = round((float(s1 or 0) + float(s2 or 0)) / n, 1) if n else 5.0
    except Exception:  # noqa: BLE001
        n, avg = len(out), 5.0
    n = max(n, len(out))
    return {"rating": avg, "count": n, "reviews": out[:9], "url": "", "src": "crm", "title": cfg.get("title") or "Відгуки пацієнтів",
            "label": f"{n} {_plural(n, 'відгук', 'відгуки', 'відгуків')}", "tx": cfg.get("tx", "")}


def mix_reviews(db: Session, g: dict | None) -> dict | None:
    """Блок відгуків сайту: рейтинг — середня оцінка пацієнтів з опитувань після візиту (усі оцінки, не лише «5»);
    картки — Google упереміш із відгуками з опитувань (5★, з текстом). Рейтинг Google показується окремо, як є."""
    from . import reviews as rv
    from sqlalchemy import select
    from ..models import ReviewArchive, Review
    rt = rv.rating(db)
    if not rt or not rt.get("count") or rt.get("avg") is None:
        return g
    own = []
    for x in db.scalars(select(Review).where(Review.text.is_not(None), Review.avg >= 5).order_by(Review.answered_at.desc().nullslast()).limit(20)):
        own.append({"author": "Відгук після візиту", "when": x.answered_at.strftime("%m.%Y") if x.answered_at else "", "rating": 5, "src": "crm",
                    "text": " ".join((x.text or "").split())})
    for x in db.scalars(select(ReviewArchive).where(ReviewArchive.text.is_not(None), ReviewArchive.avg >= 5, ReviewArchive.hidden.is_not(True))
                        .order_by(ReviewArchive.at.desc().nullslast(), ReviewArchive.id.desc()).limit(20)):
        own.append({"author": "Відгук після візиту", "when": x.at.strftime("%m.%Y") if x.at else "", "rating": 5, "src": "crm",
                    "text": " ".join((x.text or "").split())})
    own = [x for x in own if len(x["text"]) >= 40 and not re.search(r"[ыэъё]", x["text"], re.I)][:6]
    gr_ = (g or {}).get("reviews") or []
    mixed = []
    for i in range(max(len(gr_), len(own))):          # Google і опитування по черзі
        mixed += gr_[i:i + 1] + own[i:i + 1]
    n = int(rt["count"])
    return {**(g or {}), "rating": float(rt["avg"]), "count": n, "src": "mix", "reviews": mixed,
            "label": f"{n} {_plural(n, 'відгук', 'відгуки', 'відгуків')} пацієнтів",
            "g_rating": (g or {}).get("rating"), "g_count": (g or {}).get("count"), "url": (g or {}).get("url") or ""}

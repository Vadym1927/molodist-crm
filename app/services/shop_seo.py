def brand_seo(seg: str, name: str) -> tuple[str, str]:
    nm, what = BRANDS.get(seg, (name, "професійна косметика для домашнього догляду за шкірою."))
    t = f"{nm} — купити косметику {nm.split(' (')[0]} в Україні, ціни | MOLODIST"

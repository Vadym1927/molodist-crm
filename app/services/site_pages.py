_cache: dict = {"at": 0.0, "hosts": set()}


def cfg(db: Session) -> dict:
    st = db.get(SyncState, KEY)
    try:
        d = json.loads(st.value) if st and st.value else {}
    except ValueError:
        d = {}
    return {**DEFAULT, **d}


def save_cfg(db: Session, d: dict) -> None:
    db.merge(SyncState(key=KEY, value=json.dumps({k: v for k, v in d.items() if k in DEFAULT}, ensure_ascii=False), updated_at=datetime.utcnow()))
    db.commit()
    _cache["at"] = 0.0


def hosts() -> set[str]:
    """Домени сайту (для middleware): кеш на 60 с, без запиту до БД на кожен запит."""
    if time.time() - _cache["at"] > 60:
        try:
            from ..models import SessionLocal
            with SessionLocal() as db:
                _cache["hosts"] = {h.strip().lower() for h in cfg(db)["hosts"] if h.strip()}
        except Exception:  # noqa: BLE001
            pass
        _cache["at"] = time.time()
    return _cache["hosts"]



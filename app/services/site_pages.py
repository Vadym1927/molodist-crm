def _promo_on(p: dict | None, today: date | None = None) -> bool:
    if not p:
        return False
    try:
        return (today or date.today()) <= date.fromisoformat(p["until"])
    except (KeyError, ValueError):
        return True


def prices(db: Session, page: dict, today: date | None = None) -> list[dict]:
    """Групи цін сторінки: ціни й наявність — з прайсу CRM. Немає послуги / прихована / без ціни — рядок не показуємо."""
    ids = {it[0] for g in page.get("prices", []) for it in g["items"]}
    svc = {s.id: s for s in db.scalars(select(CbService).where(CbService.id.in_(ids)))} if ids else {}
    promo = page.get("promo") if _promo_on(page.get("promo"), today) else None
    out = []
    for g in page.get("prices", []):
        rows = []
        for it in g["items"]:
            s = svc.get(it[0])
            if not s or s.active is False or not s.price or s.price < 1:
                continue
            r = {"id": s.id, "name": (it[1] if len(it) > 1 and it[1] else s.name), "note": it[2] if len(it) > 2 else "", "price": float(s.price)}
            if promo and it[0] in (g.get("promo_ids") or []):
                r["old"], r["price"] = r["price"], round(r["price"] * (100 - promo["pct"]) / 100)
            rows.append(r)
        if rows:
            out.append({"title": g["title"], "note": g.get("note", ""), "rows": rows})
    return out


def min_price(groups: list[dict]) -> float | None:
    v = [r["price"] for g in groups for r in g["rows"]]
    return min(v) if v else None


def missing(db: Session, slug: str) -> list[int]:
    """Послуги зі сторінки, яких немає в прайсі CRM або вони приховані / без ціни (для «Налаштування → Сайт»)."""
    page = PAGES[slug]
    ids = [it[0] for g in page.get("prices", []) for it in g["items"]]
    have = {s.id: s for s in db.scalars(select(CbService).where(CbService.id.in_(ids)))}
    return [i for i in ids if i not in have or have[i].active is False or not have[i].price]


def doctors(db: Session, keys: list[str], base: str = "/_site") -> list[dict]:
    rows = db.scalars(select(Doctor).where(Doctor.active.is_(True))).all()
    out = []
    for k in keys:
        d = DOCTORS[k]
        m = next((x for x in rows if d["match"] in (x.name or "").lower()), None)
        photo = media_url(f"doc-{k}.webp", base) or (m.photo_url if m and (m.photo_url or "").startswith(("https://", "/")) else "")
        out.append({"name": d["name"], "role": d["role"], "bio": d["bio"], "photo": photo,
                    "initials": "".join(w[0] for w in d["name"].split()[:2]).upper()})
    return out


def money(v: float | None) -> str:
    if v is None:
        return ""
    return f"{v:,.0f}".replace(",", " ") + " ₴"


def jsonld(page: dict, c: dict, url: str, groups: list[dict]) -> str:
    """Розмітка schema.org: медичний заклад + FAQ — для розширених сніпетів у Google."""
    clinic = {"@type": "MedicalClinic", "name": "MOLODIST", "url": c["main_url"], "telephone": c["phone"], "email": c["email"],
              "address": {"@type": "PostalAddress", "streetAddress": "вул. Князя Романа Мстиславича, 28А", "addressLocality": "Київ", "addressCountry": "UA"}}
    lo = min_price(groups)
    if lo:
        clinic["priceRange"] = f"від {money(lo)}"
    faq = {"@type": "FAQPage", "mainEntity": [{"@type": "Question", "name": q, "acceptedAnswer": {"@type": "Answer", "text": a}} for q, a in page.get("faq", [])]}
    return json.dumps({"@context": "https://schema.org", "@graph": [clinic, faq, {"@type": "WebPage", "url": url, "name": page["title"]}]}, ensure_ascii=False)

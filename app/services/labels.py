def code128(text: str) -> list[int]:
    """Текст → коди символів (набір B, для довгих цифрових рядків — C) зі старт/контроль/стоп."""
    t = "".join(ch for ch in str(text) if 32 <= ord(ch) < 127)
    if t.isdigit() and len(t) >= 4 and len(t) % 2 == 0:
        codes = [105] + [int(t[i:i + 2]) for i in range(0, len(t), 2)]
    else:
        codes = [104] + [ord(ch) - 32 for ch in t]
    chk = (codes[0] + sum(i * c for i, c in enumerate(codes[1:], 1))) % 103
    return codes + [chk, 106]


def barcode_svg(text: str, height: float = 30) -> str:
    """SVG штрихкоду (viewBox у модулях, масштабується CSS під розмір цінника)."""
    if not text:
        return ""
    x, rects = 10, []
    for c in code128(text):
        for i, w in enumerate(_P[c]):
            w = int(w)
            if i % 2 == 0:
                rects.append(f'<rect x="{x}" y="0" width="{w}" height="{height}"/>')
            x += w
    return (f'<svg class="bc" viewBox="0 0 {x + 10} {height}" preserveAspectRatio="none" xmlns="http://www.w3.org/2000/svg">'
            + "".join(rects) + "</svg>")

def _n(t: str) -> str:
    return t.lower().replace("’", "'").replace("ʼ", "'").replace("`", "'").strip(".,")


def suggest(full: str) -> str | None:
    """Нова назва «Прізвище Ім'я По батькові» або None (вже правильно / незрозуміло)."""
    parts = (full or "").split()
    if len(parts) < 2:
        return None
    a, b = _n(parts[0]), _n(parts[1])
    a_name, b_name = a in NAMES, b in NAMES
    if a_name and not b_name:
        return " ".join([parts[1], parts[0]] + parts[2:])
    return None


def plan(db: Session) -> dict:
    rows = db.scalars(select(Patient).order_by(Patient.full_name)).all()
    fix, unclear = [], []
    for p in rows:
        s = suggest(p.full_name)
        if s:
            fix.append((p.id, p.full_name, s))
        else:
            parts = (p.full_name or "").split()
            if len(parts) >= 2 and _n(parts[0]) not in NAMES and _n(parts[1]) not in NAMES and not PATRON.search(parts[-1]):
                unclear.append((p.id, p.full_name))
    return {"total": len(rows), "fix": fix, "unclear": unclear}


def apply(db: Session, ids: set[int] | None = None) -> int:
    n = 0
    for pid, _old, new in plan(db)["fix"]:
        if ids is None or pid in ids:
            p = db.get(Patient, pid)
            p.full_name = new
            n += 1
    db.commit()
    return n
